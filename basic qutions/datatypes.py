# Int

a = 10
print(a)
print(type(a))


# Float

b = 10.5
print(b)
print(type(b))


# Complex

c = 2 + 3j
print(c)
print(type(c))


# String

name = "Python"
print(name)
print(type(name))


# List

lst = [1, 2, 3]
print(lst)
print(type(lst))


# Tuple

tup = (10, 20, 30)
print(tup)
print(type(tup))


# Set

st = {1, 2, 3}
print(st)
print(type(st))


# Dictionary

d = {"Name": "Sumit", "Age": 19}
print(d)
print(type(d))


# Boolean

flag = True
print(flag)
print(type(flag))